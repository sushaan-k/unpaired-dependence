def donor_readout(R, arms_all, po_arms, reg_arms, budget, e, truth_index=0):
    """Per donor: E1 (e=1) or E2 (e=2) at one budget for the atlas, the best paired-only arm and the best form of
    reference regression, the best chosen on the pooled endpoint (as for the published envelopes)."""
    b = [int(x) for x in R[0]["budgets"]].index(budget)
    donors = sorted({str(r["donor"]) for r in R})
    num = {d: np.zeros(len(arms_all)) for d in donors}
    den = {d: 0.0 for d in donors}
    for r in R:
        d = str(r["donor"])
        sc = r["scored/primary"].astype(bool) if truth_index == 0 else r["scored/primary"].astype(bool)
        v = np.nanmean(r["score"][b, :, :, :, truth_index, e], 0)[:, sc]      # arms x scored types
        num[d] += v.sum(-1)
        den[d] += float(r["reps/primary"][sc].sum()) if e == 1 else 100.0 * int(sc.sum())
    pooled = sum(num.values()) / sum(den.values())
    best_po = max(po_arms, key=lambda a: pooled[arms_all.index(a)])
    best_reg = max(reg_arms, key=lambda a: pooled[arms_all.index(a)])
    out = {}
    for d in donors:
        if den[d] == 0:
            continue
        v = num[d] / den[d]
        out[d] = {"atlas": float(v[arms_all.index("atlas")]), "paired_only": float(v[arms_all.index(best_po)]),
                  "regression": float(v[arms_all.index(best_reg)])}
    return out, best_po, best_reg


