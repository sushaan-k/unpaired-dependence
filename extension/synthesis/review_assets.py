def draw_records():
    recs = {}
    for p in sorted(CHK.glob("*.json")):
        if p.name == "draw_scoring.json":
            continue
        r = load(p)
        recs[r["test"]] = r
    return recs


def draw_table(recs):
    """Supplementary Table: every test's curves against the mean of per-draw scores."""
    rows = []
    order = ["external", "deployment", "validation"] + sorted(k for k in recs if k.startswith("benchmark/")) \
        + sorted(k for k in recs if k.startswith("law/"))
    for k in order:
        if k not in recs:
            continue
        r = recs[k]
        chk = r.get("stored_vs_regenerated", {})
        infl = r["averaged_prediction_minus_published"]
        name = {"external": "External test", "deployment": "Bone-marrow test", "validation": "Validation test"}.get(
            k, k.replace("benchmark/", "Benchmark: ").replace("law/", "Law: ").replace("_", "\\_"))
        units = (f"{r['units_regenerated']}/{r['units']}" if "units" in r else f"{len(r['problems'])} problems")
        draws = r.get("draws")
        draws = draws[0] if isinstance(draws, list) else draws
        d_pub = r.get("max_abs_difference_per_draw_vs_published")
        d_unit = r.get("max_abs_difference_per_draw_vs_stored_unit_terms", d_pub)
        d = max(x for x in (d_pub, d_unit) if x is not None)
        msq = chk.get("max_rel_msq_difference")
        rows.append(" & ".join([name, units, str(draws), f"${sci(max(d, 1e-16))}$",
                                "--" if msq is None else f"${sci(max(msq, 1e-16))}$",
                                f"{100 * infl['median']:.1f}", f"{100 * infl['max']:.0f}"]) + " \\\\")
    lines = [HEADER, "\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
             " & Units & Draws & \\multicolumn{2}{c}{Largest difference} & "
             "\\multicolumn{2}{c}{Averaged prediction} \\\\",
             "\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
             "Test & rerun & & curve & msq & median & max \\\\", "\\midrule"]
    lines += rows + ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def draw_macros(recs, m):
    diffs, infl = [], []
    for r in recs.values():
        for key in ("max_abs_difference_per_draw_vs_published", "max_abs_difference_per_draw_vs_stored_unit_terms"):
            if r.get(key) is not None:
                diffs.append(r[key])
        infl.append(r["averaged_prediction_minus_published"])
    m["RvDrawTests"] = str(len(recs))
    m["RvDrawMaxDiff"] = f"${sci(max(diffs))}$"
    m["RvDrawInflMedianMin"] = f"{100 * min(i['median'] for i in infl):.0f}"
    m["RvDrawInflMedianMax"] = f"{100 * max(i['median'] for i in infl):.0f}"
    m["RvDrawInflMax"] = f"{100 * max(i['max'] for i in infl):.0f}"
    dep = recs.get("deployment", {})
    m["RvDrawFileIdentical"] = "identical" if dep.get("regenerated_prediction_file_identical") else "not identical"


