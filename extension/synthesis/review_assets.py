def noise_table(cal):
    """Supplementary Table: calibration ratios by study, budget and noise estimate (summed over blocks); for the
    implemented estimate, its 95% interval, its range over the eight blocks and its variation over orderings."""
    budgets = list(cal["validation"]["budgets"])
    n = len(budgets)
    lines = [HEADER, "\\begin{tabular}{@{}l" + "r" * n + "@{}}", "\\toprule",
             f" & \\multicolumn{{{n}}}{{c}}{{Paired cells}} \\\\", f"\\cmidrule(l){{2-{n + 1}}}",
             "Noise estimate & " + " & ".join(budgets) + " \\\\", "\\midrule"]
    for study, label in (("validation", "Validation test"), ("bone_marrow", "Bone-marrow test")):
        if study not in cal:
            continue
        bud = cal[study]["budgets"]
        lines.append(f"\\multicolumn{{{n + 1}}}{{@{{}}l}}{{\\textit{{{label}}}}} \\\\")
        for e, name in ESTIMATES:
            lines.append(f"{name} & " + " & ".join(f"{d['ratio'][e]['global']:.3f}" for d in bud.values()) + " \\\\")
            if e == "helmert":
                lines.append("\\quad 95\\% interval & " + " & ".join(
                    f"{d['ratio'][e]['global_ci'][0]:.3f}--{d['ratio'][e]['global_ci'][1]:.3f}" for d in bud.values())
                             + " \\\\")
                lines.append("\\quad range over blocks & " + " & ".join(
                    f"{min(d['ratio'][e]['blocks']):.2f}--{max(d['ratio'][e]['blocks']):.2f}" for d in bud.values())
                             + " \\\\")
                lines.append("\\quad order, CV (largest) & " + " & ".join(
                    f"{100 * max(d['ordering']['median_cv']):.1f}\\%" for d in bud.values()) + " \\\\")
                lines.append("\\quad order, factor range & " + " & ".join(
                    f"{max(d['ordering']['median_factor_range']):.3f}" for d in bud.values()) + " \\\\")
        for e, name in (("helmert", "Recovered (\\%), implemented"), ("jackknife", "Recovered (\\%), jackknife")):
            lines.append(f"{name} & " + " & ".join(pct(d["recovered_fraction"][e]) for d in bud.values()) + " \\\\")
        if study != "bone_marrow":
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def noise_block_table(cal):
    """Supplementary Table: the implemented estimate's calibration ratio block by block, with 95% intervals."""
    budgets = list(cal["validation"]["budgets"])
    n = len(budgets)
    lines = [HEADER, "\\begin{tabular}{@{}l" + "r" * n + "@{}}", "\\toprule",
             f" & \\multicolumn{{{n}}}{{c}}{{Paired cells}} \\\\", f"\\cmidrule(l){{2-{n + 1}}}",
             "Block (RNA/protein axes) & " + " & ".join(budgets) + " \\\\", "\\midrule"]
    for study, label in (("validation", "Validation test"), ("bone_marrow", "Bone-marrow test")):
        if study not in cal:
            continue
        bud = cal[study]["budgets"]
        lines.append(f"\\multicolumn{{{n + 1}}}{{@{{}}l}}{{\\textit{{{label}}}}} \\\\")
        for k, blk in enumerate(BLOCKS):
            lines.append(f"{blk} & " + " & ".join(
                f"{d['ratio']['helmert']['blocks'][k]:.3f}" for d in bud.values()) + " \\\\")
            lines.append(" & " + " & ".join(
                f"({d['ratio']['helmert']['blocks_ci'][k][0]:.3f}--{d['ratio']['helmert']['blocks_ci'][k][1]:.3f})"
                for d in bud.values()) + " \\\\")
        if study != "bone_marrow":
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def noise_macros(cal, m):
    for study, key in (("validation", "Val"), ("bone_marrow", "Bm")):
        if study not in cal:
            continue
        bud = cal[study]["budgets"]
        g = [d["ratio"]["helmert"]["global"] for d in bud.values()]
        m[f"RvCal{key}Min"], m[f"RvCal{key}Max"] = f"{min(g):.3f}", f"{max(g):.3f}"
        bl = [x for d in bud.values() for x in d["ratio"]["helmert"]["blocks"]]
        m[f"RvCal{key}BlockMin"], m[f"RvCal{key}BlockMax"] = f"{min(bl):.2f}", f"{max(bl):.2f}"
        j = [d["ratio"]["jackknife"]["global"] for d in bud.values()]
        m[f"RvCal{key}JackMax"], m[f"RvCal{key}JackMin"] = f"{max(j):.2f}", f"{min(j):.2f}"
        o = [d["ratio"]["own_centring"]["global"] for d in bud.values()]
        m[f"RvCal{key}OwnMin"], m[f"RvCal{key}OwnMax"] = f"{min(o):.2f}", f"{max(o):.2f}"
        q = [d["ratio"]["orthonormal"]["global"] for d in bud.values()]
        m[f"RvCal{key}OrthoMin"], m[f"RvCal{key}OrthoMax"] = f"{min(q):.3f}", f"{max(q):.3f}"
        # ordering: per block, the median over resamples of the coefficient of variation of the estimate across 20
        # orders and of the range of the block's shrinkage factor; the largest block at each budget
        cv = {B: max(d["ordering"]["median_cv"]) for B, d in bud.items()}
        fr = {B: max(d["ordering"]["median_factor_range"]) for B, d in bud.items()}
        m[f"RvCal{key}OrderCvMax"] = f"{100 * max(cv.values()):.0f}"
        m[f"RvCal{key}OrderFactorMax"] = f"{max(fr.values()):.2f}"
        m[f"RvCal{key}OrderCvHundred"] = f"{100 * cv['100']:.1f}"
        m[f"RvCal{key}OrderFactorHundred"] = f"{fr['100']:.2f}"
        m[f"RvCal{key}OrderCvEight"] = f"{100 * cv['800']:.1f}"
        m[f"RvCal{key}OrderFactorEight"] = f"{fr['800']:.3f}"
        rh = [d["recovered_fraction"]["helmert"] for d in bud.values()]
        rj = [d["recovered_fraction"]["jackknife"] for d in bud.values()]
        dd = [100 * (b - a) for a, b in zip(rh, rj)]
        m[f"RvCal{key}JackGainMin"], m[f"RvCal{key}JackGainMax"] = f"{min(dd):.1f}", f"{max(dd):.1f}"


def noise_panel(cal, at, name, title, axis_start, common, log_x):
    """Calibration ratio (mean noise estimate over the variance across independent resamples) against paired cells."""
    styles = {"helmert": "color=propcol,line width=1.1pt,mark=*,mark size=1.4pt",
              "jackknife": "color=semicol,line width=.8pt,mark=square*,mark size=1.2pt",
              "own_centring": "color=meancol,line width=.8pt,mark=x,mark size=1.8pt"}
    lines = [axis_start(at, name, ".3", "3.2cm", log_x),
             " xmin=20,xmax=1000,ymin=.6,ymax=1.7,xtick={25,50,100,200,400,800},xticklabels={25,50,100,200,400,800},",
             " ytick={.6,.8,1,1.2,1.4,1.6},xlabel={Paired cells},ylabel={Estimated / actual noise},",
             f" title={{{title}}},", common + "]",
             "\\draw[dashed,black!45] (axis cs:20,1) -- (axis cs:1000,1);"]
    for study, dash in (("validation", ""), ("bone_marrow", ",densely dashed")):
        if study not in cal:
            continue
        bud = cal[study]["budgets"]
        for e, style in styles.items():
            pts = " ".join(f"({B},{min(max(d['ratio'][e]['global'], .6), 1.7):.4f})" for B, d in bud.items())
            lines.append(f"\\addplot[{style}{dash}] coordinates {{ {pts} }};")
    lines.append("\\end{axis}")
    return lines


