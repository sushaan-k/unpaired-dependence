def load(path):
    return json.loads(Path(path).read_text())


def signed(text):
    return "\\ensuremath{-}" + text[1:] if text.startswith("-") else text


def pct(v, digits=None):
    p = 100 * v
    if digits is None:
        digits = 1 if abs(p) < 10 else 0
    return signed(f"{p:.{digits}f}")


def ratio(v, digits=2):
    return f"{v:.{digits}f}"


def sci(v):
    """A small positive number as a power of ten in LaTeX math, e.g. 4 x 10^-10."""
    if v == 0:
        return "0"
    e = int(np.floor(np.log10(v)))
    m = v / 10 ** e
    return f"{m:.0f}\\times10^{{{e}}}" if round(m) != 1 else f"10^{{{e}}}"


def cells(c, rel):
    return f"$>${c:.0f}" if rel == ">" else (f"$\\leq${c:.0f}" if rel == "<=" else f"{c:.0f}")


