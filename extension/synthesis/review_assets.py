def pilot_summary(per, targets=("0.3", "0.5", "0.7"), pilots=("50", "100", "200")):
    """Per target and pilot size, over problems (each weighted alike): the distribution of each problem's median
    achieved recovered fraction, the share of replicates reaching the target (and within 0.05), the flagged share,
    and the chosen total over the paired cells the observed curve needs."""
    out = {}
    for a in targets:
        rec = {}
        for m_ in pilots + ("reservoir",):
            med, reach, near, flag, tot, ratio, by_set = [], [], [], [], [], [], {}
            for name, probs in per.items():
                for tag, pr in probs.items():
                    ta = pr["targets"][a]
                    if m_ == "reservoir":
                        if "reservoir_law" not in ta:
                            continue
                        x = np.array(ta["reservoir_law"]["achieved"])
                        t = np.full(len(x), ta["reservoir_law"]["total"], float)
                        f = np.zeros(len(x), bool)
                    else:
                        v = ta["pilots"].get(m_) or next((w for w in ta["pilots"].values()
                                                          if int(m_) in w["labels"]), None)
                        if v is None:
                            continue
                        x, t, f = np.array(v["achieved"]), np.array(v["total"], float), np.array(v["flagged"])
                    med.append(float(np.median(x)))
                    reach.append(float(np.mean(x >= float(a))))
                    near.append(float(np.mean(x >= float(a) - 0.05)))
                    flag.append(float(np.mean(f)))
                    tot.append(float(np.median(t)))
                    if ta["observed_relation"] == "=":
                        ratio.append(float(np.median(t / ta["observed_cells"])))
                    by_set.setdefault(name, []).append(float(np.mean(x >= float(a) - 0.05)))
            if not med:
                continue
            rec[m_] = {"problems": len(med), "median_achieved": float(np.median(med)),
                       "iqr_achieved": np.percentile(med, [25, 75]).tolist(),
                       "share_reaching": float(np.mean(reach)), "share_within": float(np.mean(near)),
                       "share_flagged": float(np.mean(flag)), "median_total": float(np.median(tot)),
                       "median_total_over_needed": float(np.median(ratio)) if ratio else None,
                       "problems_with_needed": len(ratio),
                       "within_by_dataset": {k: float(np.mean(v)) for k, v in by_set.items()}}
        out[a] = rec
    return out


