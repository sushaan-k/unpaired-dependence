def legend_rows(anchor, entries, columns, shift="-2pt", side="north"):
    """A legend without an axis below the point anchor; side north centres it there, north west and north east
    align its left or right edge with the point."""
    x = {"north": "0.5", "north west": "0", "north east": "1"}[side]
    out = ["\\begin{axis}[hide axis,scale only axis,width=1pt,height=1pt,xmin=0,xmax=1,ymin=0,ymax=1,"
           f"at={{({anchor})}},anchor={side},yshift={shift},legend style={{draw=none,font=\\sffamily\\scriptsize,"
           f"at={{({x},0.5)}},anchor={side},legend columns={columns},column sep=5pt,cells={{anchor=west}}}}]"]
    for style, label in entries:
        out += [f"\\addlegendimage{{{style}}}", f"\\addlegendentry{{{label}}}"]
    out.append("\\end{axis}")
    return out


