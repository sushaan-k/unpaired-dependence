def cell_pct(v):
    return pct(v, 0) if abs(100 * v) >= 10 else pct(v, 1)


def deploy_table(dep):
    b = dep["budgets"]
    p = dep["targets"]["0.5"]["cells"]
    lines = [HEADER,
             "\\begin{tabular}{@{}l" + "r" * len(b) + "r@{}}", "\\toprule",
             " & \\multicolumn{%d}{c}{Recovered (\\%%) with paired cells} & Paired cells \\\\" % len(b),
             "\\cmidrule(lr){2-%d}" % (len(b) + 1),
             "Unpaired cells & " + " & ".join(str(x) for x in b) + " & to the target \\\\", "\\midrule"]
    for arm, lab in ARM_LABELS:
        c = p[arm]
        cells = f"$>${c['cells']:.0f}" if c["relation"] == ">" else f"{c['cells']:.0f}"
        lines.append(f"{lab} & " + " & ".join(cell_pct(v) for v in dep["rf"][arm]) + f" & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def site_table(dep):
    lines = [HEADER,
             "\\begin{tabular}{@{}lrrr@{}}", "\\toprule",
             "Site & Best recovery (\\%) & Other sites & Other sites, RNA from nuclei \\\\", "\\midrule"]
    for s, r in sorted(dep["sites"].items()):
        rel = r["relations"]
        def show(num_arm, den_arm, v):
            lower = rel[num_arm] == ">" and rel[den_arm] != ">"
            both = rel[num_arm] == ">" and rel[den_arm] == ">"
            return "n.r." if both else (("$\\geq$" if lower else "") + fac(v))
        lines.append(f"{s} & {pct(r['level'], 0)} & "
                     f"{show('paired_only', 'proposed_other', r['other_vs_paired_only'])} & "
                     f"{show('paired_only', 'proposed_assay', r['assay_vs_paired_only'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


