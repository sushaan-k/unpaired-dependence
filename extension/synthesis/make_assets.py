def sensitivity_macros(val, con, m):
    """After scoring: the validation's saving with the budget axis counted in contrast rows (mean rows at each budget,
    the same interpolation as the test), and the bone-marrow paired-only control under both centrings."""
    grun = _load_module("grun", EXT / "generality" / "grun.py")
    p = val["targets"]["0.5"]
    rows = [val["audit"]["accounting"][str(B)]["rows_contrasts"] for B in val["budgets"]]
    na, ra = grun.needed(val["rf"]["atlas"], p["target"], rows)
    npo, rpo = grun.needed(val["rf"]["paired_only"], p["target"], rows)
    assert (ra, rpo) == ("=", ">")
    m["VlRowsAtlas"], m["VlRowsMax"], m["VlSaveAtlasRows"] = f"{na:.0f}", f"{rows[-1]:.0f}", fac(npo / na)
    b = con["budgets"]
    for arm, key in (("paired_only", "DpPoDf"), ("c_paired_only", "DpPoCon")):
        for B in (25, 50, 100):
            m[f"{key}{WORD_BUDGET[B]}"] = pct(con["rf"][arm][b.index(B)])
    # the two centrings at the larger budgets
    big = [abs(con["rf"]["c_paired_only"][b.index(B)] - con["rf"]["paired_only"][b.index(B)]) for B in (400, 800)]
    assert max(big) < 0.001, big
    lead = [con["rf"]["c_paired_only"][b.index(B)] >= con["rf"]["paired_only"][b.index(B)] for B in (25, 50, 100, 200)]
    assert all(lead), lead


