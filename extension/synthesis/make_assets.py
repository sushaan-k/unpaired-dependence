def row(label, cells):
    """A table row: the label, then the cells, separated by ampersands."""
    return f"{label} & " + " & ".join(cells) + " \\\\"


def signed(text):
    return "\\ensuremath{-}" + text[1:] if text.startswith("-") else text


def pct(v, digits=None):
    p = 100 * v
    if digits is None:
        digits = 1 if abs(p) < 10 else 0
    return signed(f"{p:.{digits}f}")


def fac(v):
    return f"{v:.2f}" if v < 1.15 else f"{v:.1f}"


def thousands(n):
    return f"{int(round(n)):,}"


def edt(stamp, date=True):
    """A freeze time 'YYYY-MM-DD HH:MM:SS EDT' as '19:35 EDT on 28 September 2026', or as '19:35 EDT'."""
    day, clock = stamp.split()[:2]
    if not date:
        return f"{clock[:5]} EDT"
    d = datetime.strptime(day, "%Y-%m-%d")
    return f"{clock[:5]} EDT on {d.day} {d:%B %Y}"


