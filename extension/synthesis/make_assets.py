def cells_text(c):
    return {">": "$>$", "<=": "$\\leq$"}.get(c["relation"], "") + f"{c['cells']:.0f}"


def fac2(v):
    """A ratio of paired cells near one keeps two decimals, so that it and its interval read alike; within 0.005
    of one it keeps three, so that a bound just above or below one is not printed as one."""
    if v != 1 and abs(v - 1) < 0.005:
        return f"{v:.3f}"
    return f"{v:.2f}" if v < 2 else f"{v:.1f}"


def cells_ci(c, top=800):
    """Paired cells needed with its interval; a resampled curve that never reached the target counts as more than
    the largest budget."""
    hi = f"$>${top}" if c["ci"][1] >= top - 0.5 else f"{c['ci'][1]:.0f}"
    return cells_text(c) + (f" ({c['ci'][0]:.0f}--{hi})" if c["relation"] == "=" else "")


def ratio_text(r):
    pre = "at least " if r["numerator_relation"] == ">" and r["denominator_relation"] != ">" else ""
    return pre + fac2(r["ratio"])


def pval_text(p, res):
    """A bootstrap P-value; at the resolution of the resamples, its bound rounded up to one digit."""
    if p <= res * 1.0001:
        e = int(np.floor(np.log10(p)))
        return f"$\\leq{int(np.ceil(p / 10 ** e - 1e-9))}\\times10^{{{e}}}$"
    return f"{p:.2g}"


def sd(v):
    """A difference of fractions in percentage points, signed."""
    return signed(f"{100 * v:.1f}")


def ci_pts(lo, hi):
    """An interval of differences in percentage points: an en dash between non-negative bounds, "to" otherwise."""
    return f"{sd(lo)}--{sd(hi)}" if lo >= 0 else f"{sd(lo)} to {sd(hi)}"


def geq(text):
    return text.replace("at least ", "$\\geq$")


