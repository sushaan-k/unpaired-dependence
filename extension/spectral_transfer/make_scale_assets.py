    donors = list(d1["donors"])
    rigor = json.loads(RIGOR.read_text())
    rows = []
    for y, (arm, label) in enumerate(reversed(ARM_LABELS), start=1):
        if arm in RIGOR_KEY:
            values = [rigor[d][RIGOR_KEY[arm]]["E"] for d in donors]
        else:
            values = [d1["donors"][d]["arms"][arm]["cov_rel_error"] for d in donors]
        rows.append((y, arm, FIGURE_LABELS[arm], values))
    ticks = ",".join(str(y) for y, *_ in rows)
    labels = ",".join("{" + label + "}" for _, _, label, _ in rows)
    points = "\n ".join(" ".join(f"({min(v, 1.95):.4f},{y + 0.18 * (k / (len(vals) - 1) - 0.5):.3f})" for k, v in enumerate(vals))
                        for y, _, _, vals in rows)
    means = " ".join(f"({min(np.mean(vals), 1.95):.4f},{y})" for y, _, _, vals in rows)
    clipped = [f"\\node[font=\\tiny,anchor=west,black!55] at (axis cs:1.96,{y}) {{{np.mean(vals):.1f}}};"
               for y, _, _, vals in rows if np.mean(vals) > 1.95]
