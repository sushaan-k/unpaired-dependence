def table(scale, d1, d2, d3):
    s1, s2 = scale["D1_leave_one_donor_out"], scale["D2_healthy_to_colitis"]

    def cell(summary, arm, metric, digits=3):
        value = summary["mean"][metric].get(arm)
        if value is None:
            return "--"
        text = f"{abs(value):.{digits}f}" if abs(value) < 100 else f"{abs(value):,.0f}".replace(",", "{,}")
        return f"$-{text}$" if value < 0 else text

    lines = []
    first = {"pf_means_closed_form": "Pairing-free, means (first version)",
             "pf_lowrank_closed_form": "Pairing-free, rank 8 (first version)"}
    for arm, label in ARM_LABELS + [("first_order", "First-order formula"),
                                    ("pf_means_regression", "Pairing-free means, regression (first version)"),
                                    ("pf_lowrank_regression", "Pairing-free rank 8, regression (first version)")]:
        lines.append(f"{first.get(arm, label)} & {cell(s1, arm, 'cov_rel_error')} & {cell(s1, arm, 'cov_corr')} & "
                     f"{cell(s1, arm, 'r2')} & {cell(s2, arm, 'cov_rel_error')} & {cell(s2, arm, 'r2')}\\\\")
    rigor = json.loads(RIGOR.read_text())
    for key, label in (("pf_means", "Pairing-free, means (corrected)"),
                       ("pf_moment", "Pairing-free, rank 8 (corrected)")):
        value = np.mean([rigor[d][key]["E"] for d in d1["donors"]])
        lines.append(f"{label} & {value:.3f} & -- & -- & -- & --\\\\")
    return ("% Generated by extension/spectral_transfer/make_scale_assets.py. Do not edit.\n"
            "\\begin{tabularx}{\\textwidth}{@{}Yrrrrr@{}}\n\\toprule\n"
            "& \\multicolumn{3}{c}{Leave one donor out ($n=12$)} & \\multicolumn{2}{c}{Healthy to colitis ($n=8$)}\\\\\n"
            "\\cmidrule(lr){2-4}\\cmidrule(l){5-6}\n"
            "Prediction & Error & Correlation & $R^2$ & Error & $R^2$\\\\\n\\midrule\n"
            + "\n".join(lines) + "\n\\bottomrule\n\\end{tabularx}\n")


def markdown(binary, scale, perm, curve):
    s1, s2 = scale["D1_leave_one_donor_out"], scale["D2_healthy_to_colitis"]
    lines = ["# Results (generated by make_scale_assets.py; do not edit)", "",
             "## Nine-marker binary panel: share of the full-pattern gain retained", "",
             "| Cohort | Pairwise, exact | 95% interval | Closed form | 95% interval | First-order |",
             "|---|---:|---:|---:|---:|---:|"]
    for c in COHORTS:
        e = binary["cohorts"][c]
        lines.append(f"| {c} | {pct(e['pairwise_exact_gain_retained'])}% | "
                     f"{pct(e['pairwise_exact_gain_retained_95'][0])}-{pct(e['pairwise_exact_gain_retained_95'][1])}% | "
                     f"{pct(e['closed_form_gain_retained'])}% | "
                     f"{pct(e['closed_form_gain_retained_95'][0])}-{pct(e['closed_form_gain_retained_95'][1])}% | "
                     f"{pct(e['first_order_gain_retained'], 0)}% |")
    lines += ["", f"## Colon panel ({s1['genes']} genes x {s1['proteins']} proteins)", "",
              "Mean over recipients; error = relative Frobenius error of the predicted cross-covariance "
              "against the held-out paired cross-covariance (lower is better).", "",
              "| Prediction | D1 error | D1 correlation | D1 R^2 | D2 error | D2 R^2 |", "|---|---:|---:|---:|---:|---:|"]
    for arm, label in ARM_LABELS:
        def get(summary, metric):
            value = summary["mean"][metric].get(arm)
            return "-" if value is None else (f"{value:.3f}" if abs(value) < 100 else f"{value:.3g}")
        lines.append(f"| {label} | {get(s1, 'cov_rel_error')} | {get(s1, 'cov_corr')} | {get(s1, 'r2')} | "
                     f"{get(s2, 'cov_rel_error')} | {get(s2, 'r2')} |")
    lines += ["", "Primary contrasts, closed form minus comparator (Bonferroni over four):", ""]
    for design, summary in (("D1", s1), ("D2", s2)):
        for comp, c in summary["primary_contrasts"].items():
            lines.append(f"- {design} vs {comp}: {c['mean_difference']:.4f} "
                         f"({c['bootstrap_familywise'][0]:.4f} to {c['bootstrap_familywise'][1]:.4f}); "
                         f"closed form better in {c['donors_favouring_target']}/{len(summary['donors'])}")
    obs = np.mean([v["closed_form"]["observed"] for v in perm.values()])
    null = np.mean([v["closed_form"]["null_mean"] for v in perm.values()])
    lines += ["", f"Pairing-free negative control (primary estimator): observed mean error {obs:.3f}, "
              f"derangement mean {null:.3f}; p = 1/201 for each of {len(perm)} donors.", "",
              "Learning curve (mean error): " + ", ".join(
                  f"{size} biopsies {np.mean([np.mean(v[size]) for v in curve.values()]):.3f}" for size in ("5", "10", "15")),
              "", "D2 was not run for the pairing-free arms. All analyses are retrospective; see PLAN.md.",
              "", "The pairing-free rows above are the first version. A corrected re-analysis "
              "(../cross_study/colon_pf_rigor.py: disjoint cell halves, donor-grouped folds, extended grids, "
              "converged fits, donor-aware permutations) gives mean error "
              + ", ".join(f"{k} {np.mean([v[k]['E'] for v in json.loads(RIGOR.read_text()).values()]):.3f}"
                          for k in ("pf_means", "pf_moment"))
              + "; Figure 3b of the revision shows the corrected values."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--results-md", type=Path, default=R / "RESULTS.md")
    args = parser.parse_args()
    binary, scale = load("binary_released.json"), load("scale_summary.json")
    d1, d2, d3 = load("d1_lodo.json"), load("d2_hc_to_uc.json"), load("d3_pairing_free.json")
    perm, curve = load("d3_permutation_control.json"), load("d3_learning_curve.json")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "scale_macros.tex").write_text(macros(binary, scale, perm, curve, d1, d3))
    (args.out / "scale_figure.tex").write_text(figure(binary, d1, d3, perm))
    (args.out / "scale_table.tex").write_text(table(scale, d1, d2, d3))
    args.results_md.write_text(markdown(binary, scale, perm, curve))
    print("wrote scale_macros.tex, scale_figure.tex, scale_table.tex to", args.out)


if __name__ == "__main__":
    main()
