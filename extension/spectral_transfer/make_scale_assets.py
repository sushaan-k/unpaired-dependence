#!/usr/bin/env python3
"""LaTeX macros, figure and table for the second-order transfer results.

Reads results/binary_released.json, results/scale_summary.json,
results/d1_lodo.json, results/d2_hc_to_uc.json, results/d3_pairing_free.json,
results/d3_permutation_control.json and results/d3_learning_curve.json.

    python make_scale_assets.py --out ../../revision/source
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
R = HERE / "results"
COHORTS = ("Cambridge", "Newcastle", "T-ALL", "Colon")
KEY = {"Cambridge": "Cam", "Newcastle": "New", "T-ALL": "Tall", "Colon": "Colon"}
ARM_LABELS = [
    ("independence", "Independence"),
    ("variances_only", "Closed form, variances only"),
    ("reference_corr", "Reference correlation"),
    ("reference_cov", "Reference covariance"),
    ("regression", "Reference regression"),
    ("cell_coupling", "Exact coupling of cells"),
    ("closed_form", "Closed form"),
    ("pf_means_closed_form", "Pairing-free, means"),
    ("pf_lowrank_closed_form", "Pairing-free, rank 8"),
    ("oracle", "Own paired half (not permitted)"),
]


FIGURE_LABELS = {
    "independence": "Independence", "variances_only": "Variances only",
    "reference_corr": "Reference correlation", "reference_cov": "Reference covariance",
    "regression": "Reference regression", "cell_coupling": "Cell coupling",
    "closed_form": "Closed form", "pf_means_closed_form": "No pairs: means",
    "pf_lowrank_closed_form": "No pairs: rank 8", "oracle": "Own paired half",
}


def load(name):
    return json.loads((R / name).read_text())


def num(x, d):
    text = f"{abs(x):.{d}f}"
    return f"\\ensuremath{{-}}{text}" if x < 0 and float(text) != 0 else text


def pct(x, d=1):
    return num(100 * x, d)


def big(x):
    text = f"{abs(x):,.0f}".replace(",", "{,}")
    return f"\\ensuremath{{-}}{text}" if x < 0 else text


def macros(binary, scale, perm, curve, d1, d3):
    lines = ["% Generated by extension/spectral_transfer/make_scale_assets.py. Do not edit."]

    def add(name, value):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    for c in COHORTS:
        e = binary["cohorts"][c]
        k = KEY[c]
        add(f"SoPair{k}", pct(e["pairwise_exact_gain_retained"]))
        add(f"SoPairLo{k}", pct(e["pairwise_exact_gain_retained_95"][0]))
        add(f"SoPairHi{k}", pct(e["pairwise_exact_gain_retained_95"][1]))
        add(f"SoClosed{k}", pct(e["closed_form_gain_retained"]))
        add(f"SoClosedLo{k}", pct(e["closed_form_gain_retained_95"][0]))
        add(f"SoClosedHi{k}", pct(e["closed_form_gain_retained_95"][1]))
        add(f"SoFirst{k}", pct(e["first_order_gain_retained"], 0))
    add("SoClipped", str(binary["clipped_cells"]["closed_form"]))
    pair = [binary["cohorts"][c]["pairwise_exact_gain_retained"] for c in COHORTS]
    add("SoPairMin", f"{100 * min(pair):.0f}")
    add("SoPairMax", f"{100 * max(pair):.0f}")
    closed = [binary["cohorts"][c]["closed_form_gain_retained"] for c in COHORTS]
    add("SoClosedMin", f"{100 * min(closed):.0f}")
    add("SoClosedMax", f"{100 * max(closed):.0f}")

    s1 = scale["D1_leave_one_donor_out"]
    add("ScDonors", str(len(s1["donors"])))
    add("ScGenes", str(s1["genes"]))
    add("ScProteins", str(s1["proteins"]))
    add("ScPairs", f"{s1['genes'] * s1['proteins']:,}".replace(",", "{,}"))
    mean = s1["mean"]
    names = {"independence": "Indep", "variances_only": "Var", "reference_corr": "RefCorr",
             "reference_cov": "RefCov", "regression": "Reg", "cell_coupling": "Cells",
             "closed_form": "Closed", "first_order": "First", "oracle": "Oracle",
             "pf_means_closed_form": "PfMeans", "pf_lowrank_closed_form": "PfLow",
             "pf_means_regression": "PfMeansReg", "pf_lowrank_regression": "PfLowReg"}
    for arm, short in names.items():
        if arm in mean["cov_rel_error"]:
            err = mean["cov_rel_error"][arm]
            add(f"ScErr{short}", num(err, 3) if abs(err) < 100 else big(err))
            add(f"ScCorr{short}", num(mean["cov_corr"][arm], 3))
            r2 = mean["r2"][arm]
            add(f"ScRsq{short}", num(r2, 3) if abs(r2) < 100 else big(r2))
    for comp, short in (("variances_only", "Var"), ("regression", "Reg"), ("reference_corr", "RefCorr"),
                        ("reference_cov", "RefCov")):
        c = s1["primary_contrasts"][comp]
        add(f"ScDiff{short}", num(c["mean_difference"], 3))
        add(f"ScDiffLo{short}", num(c["bootstrap_familywise"][0], 3))
        add(f"ScDiffHi{short}", num(c["bootstrap_familywise"][1], 3))
        add(f"ScWins{short}", f"{c['donors_favouring_target']}/{len(s1['donors'])}")
    cells = s1["cells_vs_closed_form"]["closed_form"]
    add("ScDiffCells", num(cells["mean_difference"], 3))
    add("ScDiffLoCells", num(cells["bootstrap_95"][0], 3))
    add("ScDiffHiCells", num(cells["bootstrap_95"][1], 3))
    pf = s1["pairing_free_vs_paired"]["pf_lowrank_closed_form"]
    for comp, short in (("closed_form", "Closed"), ("regression", "Reg"), ("variances_only", "Var"),
                        ("independence", "Indep")):
        add(f"PfDiff{short}", num(pf[comp]["mean_difference"], 3))
        add(f"PfDiffLo{short}", num(pf[comp]["bootstrap_familywise"][0], 3))
        add(f"PfDiffHi{short}", num(pf[comp]["bootstrap_familywise"][1], 3))
    gap_closed = mean["cov_rel_error"]["independence"] - mean["cov_rel_error"]["closed_form"]
    gap_pf = mean["cov_rel_error"]["independence"] - mean["cov_rel_error"]["pf_lowrank_closed_form"]
    add("PfShareOfPaired", pct(gap_pf / gap_closed, 0))
    gap_means = mean["cov_rel_error"]["independence"] - mean["cov_rel_error"]["pf_means_closed_form"]
    add("PfShareOfPairedMeans", pct(gap_means / gap_closed, 0))
    s2 = scale["D2_healthy_to_colitis"]
    for arm, short in names.items():
        if arm in s2["mean"]["cov_rel_error"]:
            e2, r2b = s2["mean"]["cov_rel_error"][arm], s2["mean"]["r2"][arm]
            add(f"HcErr{short}", num(e2, 3) if abs(e2) < 100 else big(e2))
            add(f"HcRsq{short}", num(r2b, 3) if abs(r2b) < 100 else big(r2b))
    for comp, short in (("variances_only", "Var"), ("regression", "Reg")):
        c = s2["primary_contrasts"][comp]
        add(f"HcDiff{short}", num(c["mean_difference"], 3))
        add(f"HcDiffLo{short}", num(c["bootstrap_familywise"][0], 3))
        add(f"HcDiffHi{short}", num(c["bootstrap_familywise"][1], 3))
    add("HcRecipients", str(len(s2["donors"])))
    obs = np.array([v["closed_form"]["observed"] for v in perm.values()])
    null = np.array([v["closed_form"]["null_mean"] for v in perm.values()])
    add("PcObs", num(obs.mean(), 3))
    add("PcNull", num(null.mean(), 3))
    add("PcPerms", "200")
    add("PcP", "1/201")
    add("PcDonors", str(len(perm)))
    sizes = ("5", "10", "15")
    for size in sizes:
        add(f"LcErr{['Five', 'Ten', 'Fifteen'][sizes.index(size)]}", num(np.mean([np.mean(v[size]) for v in curve.values()]), 3))
    add("LcErrAll", num(np.mean([np.mean([x for k, x in v.items() if k not in sizes][0]) for v in curve.values()]), 3))
    edge = sum(d["ridge_scale"] == 1e-3 for d in d3["donors"].values())
    add("PfRidgeEdge", f"{edge} of {len(d3['donors'])}")
    add("PfSamples", f"{min(d['training_samples'] for d in d3['donors'].values())}--{max(d['training_samples'] for d in d3['donors'].values())}")
    return "\n".join(lines) + "\n"


RIGOR = HERE.parent / "cross_study" / "results" / "colon_rigor.json"
RIGOR_KEY = {"pf_means_closed_form": "pf_means", "pf_lowrank_closed_form": "pf_moment"}


